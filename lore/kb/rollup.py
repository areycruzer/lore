"""Weekly rollups, stale checks and lint. Deterministic; run by cron."""
from __future__ import annotations

import datetime as dt

from lore.kb.store import KnowledgeBase, iso_week


def weekly_rollup(kb: KnowledgeBase, date: str, actor: str = "cron:weekly-rollup", commit: bool = True, lookback_weeks: int = 6) -> str:
    end = dt.date.fromisoformat(date)
    start = end - dt.timedelta(weeks=lookback_weeks)
    y, w = iso_week(end)
    rows = []
    for a in kb.list_accounts():
        acc = a["account_id"]
        cur = kb.current_events(acc)
        recent = [e for e in cur if start <= dt.date.fromisoformat(str(e.get("occurred_at"))) <= end]
        sig = [e for e in recent if e.get("kind") in ("signal", "ops_request", "budget", "timeline", "objection", "churn_risk")
               and not (e.get("kind") == "ops_request" and not (e.get("extra") or {}).get("bridge"))]
        if sig:
            rows.append((acc, a["name"], a.get("owner"), sig))
    L = [f"# Signals {y}-W{w:02d}", "", f"_What moved across all accounts from {start} to {end}. Generated by {actor}._", ""]
    for acc, name, owner, sig in sorted(rows, key=lambda r: -len(r[3])):
        L.append(f"## [{name}](../../accounts/{acc}/index.md) ({acc}, owner {owner})")
        for e in sorted(sig, key=lambda e: str(e.get("occurred_at")), reverse=True)[:6]:
            gate = f" gate `{e.get('gate')}`" if e.get("gate") else ""
            L.append(f"- {e.get('occurred_at')} [{e.get('kind')}] {e.get('summary')}{gate} ({e.get('source')})")
        L.append("")
    conflicts = kb.conflicts()
    if conflicts:
        L.append("## Open contradictions")
        for c in conflicts:
            L.append(f"- `{c['id']}`: {c['winner']['summary']} vs " + "; ".join(x["summary"] for x in c["losers"]))
    rel = f"wiki/signals/{y}/W{w:02d}.md"
    kb.write_page(rel, "\n".join(L) + "\n", actor=actor, commit=commit)
    return rel


def stale_check(kb: KnowledgeBase, today: str, weeks: int = 26, actor: str = "cron:stale-check") -> list[str]:
    """Additive: writes a `stale` event for topic facts older than N weeks with no newer support."""
    cutoff = dt.date.fromisoformat(today) - dt.timedelta(weeks=weeks)
    written = []
    for a in kb.list_accounts():
        acc = a["account_id"]
        already = {(e.get("extra") or {}).get("stale_of") for e in kb.events(acc) if e.get("kind") == "stale"}
        for e in kb.current_events(acc):
            if e.get("topic") in (None, "status", "owned_products") or e.id in already or e.get("kind") == "stale":
                continue
            if dt.date.fromisoformat(str(e.get("occurred_at"))) < cutoff:
                written.append(kb.add_event({"account": acc, "kind": "stale", "summary": f"Stale: '{e.get('summary')}' has no support newer than {weeks} weeks",
                                             "source": e.get("source"), "epistemic_status": "inferred", "extra": {"stale_of": e.id}},
                                            actor=actor, rebuild=False))
    return written


def lint(kb: KnowledgeBase) -> list[str]:
    problems = []
    for a in kb.list_accounts():
        for e in kb.events(a["account_id"]):
            if not e.get("source"):
                problems.append(f"{e.path}: missing source")
            if not e.get("epistemic_status"):
                problems.append(f"{e.path}: missing epistemic_status")
            try:
                kb.quote(e.get("source"))
            except Exception as exc:  # noqa: BLE001
                problems.append(f"{e.path}: broken source {e.get('source')} ({exc})")
    ok, n = kb.verify_ledger()
    if not ok:
        problems.append(f"audit ledger hash chain broken after entry {n}")
    return problems
